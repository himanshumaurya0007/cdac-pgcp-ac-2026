public class ImplicitTypeCasting {
    public static void main(String[] args) {
        byte x = 10;
        short y = x;

        System.out.println(x);
        System.out.println(y);

        int p = 999;
        long q = p;
        
        System.out.println(p);
        System.out.println(q);
    }
}
